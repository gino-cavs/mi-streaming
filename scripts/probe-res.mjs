import { writeFile, mkdir } from 'node:fs/promises';
await mkdir('out', { recursive:true });
const UA = { 'User-Agent':'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130 Safari/537.36' };
const raw = async u => { try { const r = await fetch(u, { headers:UA, signal:AbortSignal.timeout(20000) }); return [r.status, await r.text()]; } catch (e) { return [0, 'ERR ' + e]; } };
const out = {};
let [s, t] = await raw('https://www.sofascore.com/tournament/football/argentina/campeonato-de-reserva-de-primera-division/18817');
out.page = s + ' ' + t.length; out.seasons = (t.match(/"seasons":\[[\s\S]{0,1500}/) || [''])[0]; out.embed = [...new Set(t.match(/widgets\.sofascore\.com[^"'\\ ]{0,200}/g) || [])].join('\n');
[s, t] = await raw('https://www.sofascore.com/robots.txt'); out.robots = s + '\n' + t.slice(0, 1500);
[s, t] = await raw('https://widgets.sofascore.com/'); out.widgets = s + ' ' + [...new Set(t.match(/\/embed\/[^"'\\ ]{0,120}/g) || [])].slice(0, 30).join('\n');
await writeFile('out/res.json', JSON.stringify(out, null, 1));
